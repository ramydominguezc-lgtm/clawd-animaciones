def cuadro(t):
    """Cuadro t del ciclo: personaje + rafaga derecha (t-1) + izquierda (t-6)."""
    w = LIENZO[0]
    capas = [(PERSONAJE[t], PERSONAJE_DX, PERSONAJE_DY)]
