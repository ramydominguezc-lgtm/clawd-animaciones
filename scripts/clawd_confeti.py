"""Clawd con confeti — datos de la animacion. El motor vive en `animar_pixel.py`.

De donde salio
--------------
Replica de "Confetti Claude", del articulo de Codrops "Reverse-Engineering
Claude AI's Mascot Animations with SVG and GSAP" (Ayotomiwa Wale-Durojaye,
mayo 2026) y su demo en ayotomcs.me/claude-mascot. No se midio de un video: se
extrajo el componente SVG de la demo (rectangulos + linea de tiempo GSAP), se
ejecuto en Node y se transcribio cada dibujo a la reticula de Clawd.

Lo que se midio
---------------
- Reticula del personaje: U = 16/3 px. Cuerpo 16U, banda de brazos 24U, ojos y
  patas 2U: la MISMA reticula que `clawd_caminando.py`. Por eso el lienzo del
  personaje es de 28 columnas y las patas caen en las columnas 6-21 igual que
  en la caminata.
- Suelo: y = 113 px en la demo. La ultima fila de cada pose apoya ahi, salvo A2
  y B2, que despegan 1U (es el brinco del pisoton).
- El confeti vive en su propia reticula de 5 px; aqui 1 celda = 1U.
- La demo desplaza los cuadros levantados 2 px (0.375U) respecto al agachado.
  Se ignoro: en pixel art no hay media celda, y asi los pies no brincan.
- Agachado: los largos medidos (patas 2.25U, cuerpo bajo 1.1U, brazos 4.3U,
  ojos 2.06U, cuerpo alto 4.69U) se redondearon por segmento; suman 14U.
- Los cuadros 5-7 de la demo son `matrix(-1 ...)` de los 1-3: espejo exacto.
  Se verifico contra una transcripcion independiente de esos cuadros: todas las
  filas en que discrepaban eran ruido de fase de la transcripcion espejo.

El error de la demo que NO se copio
-----------------------------------
El articulo dice "ocho cuadros a 125 ms". La demo pone el ultimo `set()` en
t = 0.875 s, asi que la linea de tiempo dura 0.875 s y el cuadro 8 (B3) nunca
se ve: el pisoton izquierdo queda con 2 cuadros y el derecho con 3. Aqui el
ciclo es el de diseno: 8 cuadros de 125 ms = 1 s, simetrico.

Ritmo
-----
- Personaje: AGACHADO A1 A2 A3 AGACHADO B1 B2 B3, un tiempo cada uno.
- Rafaga 1 (derecha): arranca 1 cuadro tarde, cuando la mano ya esta arriba.
- Rafaga 2 (izquierda): arranca 6 cuadros tarde, con el otro brazo arriba. Es
  el espejo de la rafaga 1.
- Cada rafaga recorre 8 dibujos C0-C7 y sube y baja con ALTURA_RAFAGA.

Leyenda de la rejilla
---------------------
    .  transparente      #  naranja cuerpo      @  ojo
    n  confeti naranja   a  confeti azul        r  confeti rosa
"""
